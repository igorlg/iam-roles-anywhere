class TestCreateSecretsYamlV2:
    """create_secrets_yaml must emit the v2 schema."""

    def _make_secrets(
        self,
        profiles: tuple[SopsProfile, ...] = (
            SopsProfile(
                role_name="admin",
                profile_arn="arn:aws:rolesanywhere:ap-southeast-2:123:profile/admin-p",
                role_arn="arn:aws:iam::123:role/admin",
            ),
        ),
    ) -> SopsSecrets:
        return SopsSecrets(
            certificate="CERT-PEM",
            private_key="KEY-PEM",
            trust_anchor_arn=(
                "arn:aws:rolesanywhere:ap-southeast-2:123:trust-anchor/ta"
            ),
            account_id="123456789012",
            region="ap-southeast-2",
            profiles=profiles,
        )

    def test_includes_schema_version(self) -> None:
        yaml_text = create_secrets_yaml(hostname="myhost", secrets=self._make_secrets())
        data = yaml.safe_load(yaml_text)
        assert data["schema_version"] == "v2"

    def test_top_level_fields(self) -> None:
        yaml_text = create_secrets_yaml(hostname="myhost", secrets=self._make_secrets())
        data = yaml.safe_load(yaml_text)
        assert data["certificate"] == "CERT-PEM"
        assert data["private_key"] == "KEY-PEM"
        assert "trust-anchor" in data["trust_anchor_arn"]
        assert data["account_id"] == "123456789012"
        assert data["region"] == "ap-southeast-2"

    def test_profiles_is_nested_map(self) -> None:
        yaml_text = create_secrets_yaml(hostname="myhost", secrets=self._make_secrets())
        data = yaml.safe_load(yaml_text)
        assert "profiles" in data
        assert isinstance(data["profiles"], dict)
        assert "admin" in data["profiles"]
        assert "profile_arn" in data["profiles"]["admin"]
        assert "role_arn" in data["profiles"]["admin"]

    def test_multi_profile_output(self) -> None:
        secrets = self._make_secrets(
            profiles=(
                SopsProfile(
                    role_name="admin",
                    profile_arn="arn:aws:rolesanywhere:ap-southeast-2:123:profile/admin-p",
                    role_arn="arn:aws:iam::123:role/admin",
                ),
                SopsProfile(
                    role_name="readonly",
                    profile_arn="arn:aws:rolesanywhere:ap-southeast-2:123:profile/readonly-p",
                    role_arn="arn:aws:iam::123:role/readonly",
                ),
            ),
        )
        yaml_text = create_secrets_yaml(hostname="myhost", secrets=secrets)
        data = yaml.safe_load(yaml_text)
        assert set(data["profiles"].keys()) == {"admin", "readonly"}
        assert (
            data["profiles"]["admin"]["role_arn"] == "arn:aws:iam::123:role/admin"
        )
        assert (
            data["profiles"]["readonly"]["role_arn"]
            == "arn:aws:iam::123:role/readonly"
        )

    def test_header_comment_references_hostname(self) -> None:
        yaml_text = create_secrets_yaml(hostname="myhost", secrets=self._make_secrets())
        assert "myhost" in yaml_text
        assert yaml_text.startswith("#")  # has a header

    def test_no_scalar_profile_arn_or_role_arn_at_top_level(self) -> None:
        """v2 must not emit the v1 singular fields - they'd be ambiguous."""
        yaml_text = create_secrets_yaml(hostname="myhost", secrets=self._make_secrets())
        data = yaml.safe_load(yaml_text)
        assert "profile_arn" not in data
        assert "role_arn" not in data


