class TestParseSecretsYamlV2:
    """Reading a v2 YAML returns a matching SopsSecrets record."""

    def test_parses_all_fields(self) -> None:
        secrets = parse_secrets_yaml(V2_YAML)

        assert secrets.certificate.startswith("-----BEGIN CERTIFICATE-----")
        assert "v2cert" in secrets.certificate
        assert secrets.private_key.startswith("-----BEGIN EC PRIVATE KEY-----")
        assert (
            secrets.trust_anchor_arn
            == "arn:aws:rolesanywhere:ap-southeast-2:444455556666:trust-anchor/v2-ta"
        )
        assert secrets.account_id == "444455556666"
        assert secrets.region == "ap-southeast-2"

    def test_parses_profiles_as_tuple(self) -> None:
        secrets = parse_secrets_yaml(V2_YAML)

        assert len(secrets.profiles) == 2
        by_name = {p.role_name: p for p in secrets.profiles}
        assert set(by_name.keys()) == {"admin", "readonly"}
        assert by_name["admin"].role_arn == "arn:aws:iam::444455556666:role/admin"
        assert (
            by_name["readonly"].profile_arn
            == "arn:aws:rolesanywhere:ap-southeast-2:444455556666:profile/readonly-p"
        )

    def test_roundtrip_write_read(self) -> None:
        """Writing then reading v2 must preserve all fields exactly."""
        original = SopsSecrets(
            certificate="CERT",
            private_key="KEY",
            trust_anchor_arn="arn:aws:rolesanywhere:ap-southeast-2:123:trust-anchor/ta",
            account_id="123456789012",
            region="us-east-1",
            profiles=(
                SopsProfile(
                    role_name="admin",
                    profile_arn="arn:aws:rolesanywhere:us-east-1:123:profile/admin-p",
                    role_arn="arn:aws:iam::123:role/admin",
                ),
                SopsProfile(
                    role_name="readonly",
                    profile_arn="arn:aws:rolesanywhere:us-east-1:123:profile/readonly-p",
                    role_arn="arn:aws:iam::123:role/readonly",
                ),
            ),
        )
        yaml_text = create_secrets_yaml(hostname="roundtrip-host", secrets=original)
        restored = parse_secrets_yaml(yaml_text)

        assert restored.certificate == original.certificate
        assert restored.private_key == original.private_key
        assert restored.trust_anchor_arn == original.trust_anchor_arn
        assert restored.account_id == original.account_id
        assert restored.region == original.region
        # Order-insensitive compare (dict iteration may differ)
        assert set(restored.profiles) == set(original.profiles)


class TestParseSecretsYamlV1Fallback:
    """v1 YAML (flat single profile_arn/role_arn) auto-converts to v2 shape."""

    def test_parses_v1_fields(self) -> None:
        secrets = parse_secrets_yaml(V1_YAML)

        assert "v1cert" in secrets.certificate
        assert "v1key" in secrets.private_key
        assert secrets.region == "ap-southeast-2"
        assert (
            secrets.trust_anchor_arn
            == "arn:aws:rolesanywhere:ap-southeast-2:111122223333:trust-anchor/v1-ta"
        )

    def test_v1_account_id_derived_from_trust_anchor(self) -> None:
        """v1 had no account_id field - parser derives from trust_anchor_arn."""
        secrets = parse_secrets_yaml(V1_YAML)
        assert secrets.account_id == "111122223333"

    def test_v1_single_profile_lifted_into_profiles_map(self) -> None:
        """v1's scalar profile_arn+role_arn become a single entry in profiles."""
        secrets = parse_secrets_yaml(V1_YAML)
        assert len(secrets.profiles) == 1
        p = secrets.profiles[0]
        # v1 has no role name anywhere - derive from role ARN resource name
        # (the part after role/) so add-role has a stable map key to index on.
        assert p.role_name == "admin"
        assert p.role_arn == "arn:aws:iam::111122223333:role/admin"
        assert (
            p.profile_arn
            == "arn:aws:rolesanywhere:ap-southeast-2:111122223333:profile/admin-p"
        )


class TestParseSecretsYamlErrors:
    """Invalid / unsupported schema versions should fail loud."""

    def test_missing_required_v2_field_raises(self) -> None:
        broken = """\
schema_version: v2
certificate: CERT
private_key: KEY
# trust_anchor_arn missing
account_id: "123456789012"
region: us-east-1
profiles: {}
"""
        with pytest.raises(ValueError, match="trust_anchor_arn"):
            parse_secrets_yaml(broken)

    def test_unknown_schema_version_raises(self) -> None:
        future = """\
schema_version: v99
certificate: CERT
private_key: KEY
"""
        with pytest.raises(ValueError, match="schema_version"):
            parse_secrets_yaml(future)

    def test_empty_yaml_raises(self) -> None:
        with pytest.raises(ValueError):
            parse_secrets_yaml("")


